export const REPORT_TYPES = [
  "SECTION_SCHEDULE",
  "FACULTY_SCHEDULE",
  "ROOM_SCHEDULE",
  "FACULTY_LOAD",
  "ROOM_UTILIZATION",
  "COLLEGE_SUMMARY",
  "CONFLICTS_AND_EXCEPTIONS",
  "VALIDATION_AND_PREFERENCES",
  "CANDIDATE_COMPARISON",
  "PORTAL_ENCODING",
  "REVISION_HISTORY",
] as const;

export type ReportType = (typeof REPORT_TYPES)[number];
export type ReportFormat = "PDF" | "XLSX";

export interface ReportExportInput {
  termCode: string;
  scheduleId?: string;
  compareScheduleId?: string;
  reportType: ReportType;
  format: ReportFormat;
  entityFilter?: string;
  actor: string;
}

export interface ReportExportResult {
  fileName: string;
  mimeType: string;
  buffer: Buffer;
  watermark: string;
  summaryMetrics: {
    classesScheduled: number;
    conflictsDetected: number;
    facultyLoadBalanceScore: number;
    roomUtilizationPct: number;
    unmetPreferencesCount: number;
  };
}

function formatMinutesToClock(min: number): string {
  const h24 = Math.floor(min / 60);
  const m = min % 60;
  const suffix = h24 >= 12 ? "PM" : "AM";
  const h12 = h24 % 12 === 0 ? 12 : h24 % 12;
  return `${String(h12).padStart(2, "0")}:${String(m).padStart(2, "0")} ${suffix}`;
}

/**
 * Build a valid, multi-line printable PDF document (PDF 1.4 specification)
 * with header, candidate/accepted watermark, metadata, and tabular rows.
 */
function buildPrintablePdfBuffer(input: {
  title: string;
  subtitle: string;
  watermark: string;
  headers: string[];
  rows: string[][];
}): Buffer {
  const escapePdfText = (s: string) =>
    s
      .replace(/\\/g, "\\\\")
      .replace(/\(/g, "\\(")
      .replace(/\)/g, "\\)")
      .replace(/[^\x20-\x7E]/g, " ");

  const lines: string[] = [
    `ORDIQ - MSEUF College of Engineering (${input.title})`,
    input.subtitle,
    `STATUS WATERMARK: ${input.watermark}`,
    "-".repeat(95),
    input.headers.join(" | "),
    "-".repeat(95),
    ...input.rows.slice(0, 42).map((r) => r.join(" | ")),
    "-".repeat(95),
    "Generated by ORDIQ Decision-Support System (Quotation Q-2026-002). Not connected to university portal.",
  ];

  const textOps = [
    "BT",
    "/F1 9 Tf",
    "36 756 Td",
    "14 TL",
    ...lines.map((line, idx) =>
      idx === 0
        ? `(${escapePdfText(line)}) Tj`
        : `T* (${escapePdfText(line)}) Tj`,
    ),
    "ET",
  ].join("\n");

  const obj1 = "1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n";
  const obj2 = "2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n";
  const obj3 =
    "3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>\nendobj\n";
  const obj4 =
    "4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>\nendobj\n";
  const obj5 = `5 0 obj\n<< /Length ${Buffer.byteLength(textOps, "utf8")} >>\nstream\n${textOps}\nendstream\nendobj\n`;

  const header = "%PDF-1.4\n";
  const objects = [obj1, obj2, obj3, obj4, obj5];
  let offset = Buffer.byteLength(header, "utf8");
  const offsets: number[] = [];

  for (const obj of objects) {
    offsets.push(offset);
    offset += Buffer.byteLength(obj, "utf8");
  }

  const xrefStart = offset;
  const xrefLines = [
    "xref",
    `0 ${objects.length + 1}`,
    "0000000000 65535 f ",
    ...offsets.map((o) => `${String(o).padStart(10, "0")} 00000 n `),
    "trailer",
    `<< /Size ${objects.length + 1} /Root 1 0 R >>`,
    "startxref",
    String(xrefStart),
    "%%EOF\n",
  ].join("\n");

  return Buffer.from(header + objects.join("") + xrefLines, "utf8");
}

/**
 * Generate any of the 11 required Phase 6 reports in PDF or Excel (.xlsx) format,
 * using `analytics.service.ts` as the single source of truth and auditing every export.
 */
export async function generateScheduleReport(
  input: ReportExportInput,
): Promise<ReportExportResult> {
  if (
    input.format === "PDF" &&
    (input.reportType === "PORTAL_ENCODING" ||
      input.reportType === "REVISION_HISTORY")
  ) {
    throw new AppError(
      "FORMAT_NOT_SUPPORTED",
      `Report type ${input.reportType} is only exported in Excel (.xlsx) format per Phase 6 specification.`,
      422,
    );
  }

  return withAudit(
    {
      actor: input.actor,
      action: "REPORT_EXPORTED",
      entity: "ScheduleReport",
      entityId: `${input.termCode}:${input.reportType}:${input.format}`,
    },
    async () => {
      const state = getMasterDataState();
      const sched = resolveTargetSchedule(input.termCode, input.scheduleId);
      const analytics = computeScheduleAnalytics(input.termCode, sched?.id);

      const watermark =
        sched?.status === "ACCEPTED"
          ? "ACCEPTED CANDIDATE — READY FOR MANUAL PORTAL ENCODING"
          : "CANDIDATE SCHEDULE — NOT OFFICIAL — NOT FOR STUDENT RELEASE";

      let headers: string[] = [];
      let rows: string[][] = [];
      let title = "";

      switch (input.reportType) {
        case "SECTION_SCHEDULE": {
          title = "Class Schedule per Section";
          headers = [
            "Section",
            "Offering",
            "Subject",
            "Component",
            "Day",
            "Start",
            "End",
            "Room",
            "Faculty",
          ];
          const entries = (sched?.entries ?? []).filter((e) => {
            if (!input.entityFilter) return true;
            const off = state.offerings.get(e.offeringCode);
            return off?.sectionCode === input.entityFilter;
          });
          rows = entries.map((e) => {
            const off = state.offerings.get(e.offeringCode);
            const fac = state.faculty.get(e.facultyCode);
            return [
              off?.sectionCode ?? "-",
              e.offeringCode,
              off?.subjectCode ?? "-",
              componentLabel(off?.component ?? "LECTURE"),
              weekdayLabel(e.weekday),
              formatMinutesToClock(e.startMin),
              formatMinutesToClock(e.endMin),
              e.roomCode,
              fac?.name ?? e.facultyCode,
            ];
          });
          break;
        }

        case "FACULTY_SCHEDULE": {
          title = "Class Schedule per Faculty";
          headers = [
            "Faculty Code",
            "Faculty Name",
            "Day",
            "Start",
            "End",
            "Offering",
            "Section",
            "Subject",
            "Room",
          ];
          const entries = (sched?.entries ?? []).filter((e) =>
            input.entityFilter ? e.facultyCode === input.entityFilter : true,
          );
          rows = entries.map((e) => {
            const off = state.offerings.get(e.offeringCode);
            const fac = state.faculty.get(e.facultyCode);
            return [
              e.facultyCode,
              fac?.name ?? e.facultyCode,
              weekdayLabel(e.weekday),
              formatMinutesToClock(e.startMin),
              formatMinutesToClock(e.endMin),
              e.offeringCode,
              off?.sectionCode ?? "-",
              off?.subjectCode ?? "-",
              e.roomCode,
            ];
          });
          break;
        }

        case "ROOM_SCHEDULE": {
          title = "Class Schedule per Room & Laboratory";
          headers = [
            "Room Code",
            "Room Name",
            "Day",
            "Start",
            "End",
            "Offering",
            "Section",
            "Subject",
            "Faculty",
          ];
          const entries = (sched?.entries ?? []).filter((e) =>
            input.entityFilter ? e.roomCode === input.entityFilter : true,
          );
          rows = entries.map((e) => {
            const off = state.offerings.get(e.offeringCode);
            const room = state.rooms.get(e.roomCode);
            const fac = state.faculty.get(e.facultyCode);
            return [
              e.roomCode,
              room?.name ?? e.roomCode,
              weekdayLabel(e.weekday),
              formatMinutesToClock(e.startMin),
              formatMinutesToClock(e.endMin),
              e.offeringCode,
              off?.sectionCode ?? "-",
              off?.subjectCode ?? "-",
              fac?.name ?? e.facultyCode,
            ];
          });
          break;
        }

        case "FACULTY_LOAD": {
          title = "Faculty Teaching Load Report";
          headers = [
            "Faculty Code",
            "Faculty Name",
            "Program",
            "Employment",
            "Assigned Units",
            "Max Regular Units",
            "Overload Units",
            "Preparations",
            "Utilization %",
            "Status",
          ];
          const loads = computeFacultyLoads(
            input.termCode,
            sched?.id,
            input.entityFilter,
          );
          rows = loads.map((l) => [
            l.facultyCode,
            l.facultyName,
            l.programCode,
            employmentLabel(l.employmentType),
            String(l.assignedUnits),
            String(l.regularMaxUnits),
            String(l.overloadUnits),
            String(l.preparationsCount),
            `${l.utilizationPct}%`,
            loadStatusLabel(l.statusLabel),
          ]);
          break;
        }

        case "ROOM_UTILIZATION": {
          title = "Room & Laboratory Utilization Report";
          headers = [
            "Room Code",
            "Room Name",
            "Type",
            "Capacity",
            "Meetings Placed",
            "Used Minutes",
            "Available Minutes",
            "Utilization %",
          ];
          const rooms = computeRoomUtilizations(
            input.termCode,
            sched?.id,
            input.entityFilter,
          );
          rows = rooms.map((r) => [
            r.roomCode,
            r.roomName,
            r.roomType,
            String(r.capacity),
            String(r.meetingCount),
            String(r.usedMinutes),
            String(r.availableMinutes),
            `${r.utilizationPct}%`,
          ]);
          break;
        }

        case "COLLEGE_SUMMARY": {
          title = "College of Engineering Schedule Summary";
          headers = ["Metric", "Value", "Calculation / Notes"];
          rows = [
            ["Term Code", analytics.termCode, "Academic term snapshot"],
            ["Schedule Label", analytics.candidateLabel, scheduleStatusLabel(analytics.status)],
            [
              "Classes Scheduled",
              `${analytics.metrics.classesScheduled} / ${analytics.metrics.totalMeetings} (${analytics.metrics.scheduledPct}%)`,
              analytics.metricFormulas.classesScheduled,
            ],
            [
              "Conflicts Detected",
              String(analytics.metrics.conflictsDetected),
              analytics.metricFormulas.conflictsDetected,
            ],
            [
              "Faculty Load Balance Score",
              `${analytics.metrics.facultyLoadBalanceScore}%`,
              analytics.metricFormulas.facultyLoadBalanceScore,
            ],
            [
              "Room Utilization",
              `${analytics.metrics.roomUtilizationPct}%`,
              analytics.metricFormulas.roomUtilizationPct,
            ],
            [
              "Unmet Preferences",
              String(analytics.metrics.unmetPreferencesCount),
              "Count of soft preference penalties (SC-01)",
            ],
            [
              "Student Change-Request Risk Indicators",
              `${analytics.studentChangeRequestRisk.totalRiskIndicators} (${analytics.studentChangeRequestRisk.riskLevel})`,
              analytics.studentChangeRequestRisk.baselineMethodNote,
            ],
          ];
          break;
        }

        case "CONFLICTS_AND_EXCEPTIONS": {
          title = "Conflict & Documented Exceptions Report (D-18)";
          headers = [
            "Record Type",
            "Constraint Code",
            "Status",
            "Reason / Message",
            "Approved By",
          ];
          const violationRows = (
            sched?.validationReport?.violations ?? []
          ).map((v) => [
            "Rule violation",
            v.code,
            v.waived ? "Waived" : "Needs fixing",
            describeViolation(v, state, sched?.entries ?? []),
            v.waiver_reason ?? "-",
          ]);
          const exceptionRows = (sched?.exceptions ?? []).map((ex) => [
            "Documented exception",
            ex.code,
            "Approved",
            ex.reason,
            ex.approvedBy,
          ]);
          const unscheduledRows = (sched?.unscheduled ?? []).map((u) => [
            "Unscheduled class",
            unscheduledReasonLabel(u.reasonCode),
            "Not placed",
            `${u.offeringCode} (meeting ${u.meetingIndex + 1}): ${u.reasonDetail}`,
            "-",
          ]);
          rows = [...violationRows, ...exceptionRows, ...unscheduledRows];
          break;
        }

        case "VALIDATION_AND_PREFERENCES": {
          title = "ISO/IEC 25012 Data Validation & Unmet Preferences Report";
          headers = ["Category", "Code", "Entity / Faculty", "Details"];
          const readiness = getTermReadinessReport(input.termCode);
          const readinessRows = [
            [
              "ISO_25012_SCORE",
              "OVERALL",
              input.termCode,
              `Completeness ${readiness.iso25012Scores.completeness}%, Accuracy ${readiness.iso25012Scores.accuracy}%, Consistency ${readiness.iso25012Scores.consistency}%, Currentness ${readiness.iso25012Scores.currentness}%`,
            ],
            ...readiness.issues.map((i) => [
              `READINESS_${i.severity}`,
              i.code,
              i.entityCode,
              i.message,
            ]),
          ];
          const unmetRows = (
            sched?.validationReport?.quality.unmet_preferences ?? []
          ).map((u) => [
            "UNMET_PREFERENCE",
            u.code,
            u.faculty_code ?? "-",
            `${u.description} (penalty ${u.penalty})`,
          ]);
          rows = [...readinessRows, ...unmetRows];
          break;
        }

        case "CANDIDATE_COMPARISON": {
          title = "Side-by-Side Candidate Comparison Report";
          headers = [
            "Candidate Label",
            "Profile",
            "Status",
            "Solver Status",
            "Quality Score",
            "Hard Violations",
            "Unscheduled",
            "Unmet Preferences",
            "Room Utilization %",
          ];
          const termSchedIds = Array.from(state.schedules.values())
            .filter((s) => s.termCode === input.termCode)
            .map((s) => s.id);
          const comps =
            termSchedIds.length > 0
              ? compareCandidateSchedules(termSchedIds)
              : [];
          rows = comps.map((c) => [
            c.candidateLabel,
            profileLabel(c.profileName),
            scheduleStatusLabel(c.status),
            solverStatusLabel(c.solverStatus),
            String(c.qualityScore),
            String(c.hardViolationCount),
            String(c.unscheduledCount),
            String(c.unmetPreferenceCount),
            `${c.roomUtilizationPct}%`,
          ]);
          break;
        }

        case "PORTAL_ENCODING": {
          title = "MSEUF Portal Encoding Export (Manual Officer Encoding Only)";
          headers = [
            "TermCode",
            "SectionCode",
            "SubjectCode",
            "SubjectTitle",
            "Component",
            "Units",
            "DayCode",
            "StartTime",
            "EndTime",
            "RoomCode",
            "FacultyCode",
            "FacultyName",
            "CandidateWatermark",
          ];
          rows = (sched?.entries ?? []).map((e) => {
            const off = state.offerings.get(e.offeringCode);
            const subj = off ? state.subjects.get(off.subjectCode) : undefined;
            const fac = state.faculty.get(e.facultyCode);
            return [
              input.termCode,
              off?.sectionCode ?? "-",
              off?.subjectCode ?? "-",
              subj?.name ?? "-",
              componentLabel(off?.component ?? "LECTURE"),
              String(subj?.units ?? 3),
              weekdayLabel(e.weekday),
              formatMinutesToClock(e.startMin),
              formatMinutesToClock(e.endMin),
              e.roomCode,
              e.facultyCode,
              fac?.name ?? e.facultyCode,
              watermark,
            ];
          });
          break;
        }

        case "REVISION_HISTORY": {
          title = "Schedule Revision & Change History";
          headers = [
            "Change ID",
            "Schedule ID",
            "Actor",
            "Action",
            "Timestamp",
            "Before Snapshot",
            "After Snapshot",
          ];
          rows = (sched?.changes ?? []).map((c) => [
            c.id,
            c.scheduleId,
            c.actor,
            c.action,
            c.createdAt,
            JSON.stringify(c.beforeJson),
            JSON.stringify(c.afterJson),
          ]);
          break;
        }
      }

      const summaryMetrics = {
        classesScheduled: analytics.metrics.classesScheduled,
        conflictsDetected: analytics.metrics.conflictsDetected,
        facultyLoadBalanceScore: analytics.metrics.facultyLoadBalanceScore,
        roomUtilizationPct: analytics.metrics.roomUtilizationPct,
        unmetPreferencesCount: analytics.metrics.unmetPreferencesCount,
      };

      const baseSlug = `ordiq-${input.termCode.toLowerCase()}-${input.reportType.toLowerCase()}`;

      if (input.format === "PDF") {
        const pdfBuffer = buildPrintablePdfBuffer({
          title,
          subtitle: `Term: ${input.termCode} | Candidate: ${analytics.candidateLabel} | Generated: ${new Date().toISOString()}`,
          watermark,
          headers,
          rows,
        });
        return {
          fileName: `${baseSlug}.pdf`,
          mimeType: "application/pdf",
          buffer: pdfBuffer,
          watermark,
          summaryMetrics,
        };
      }

      // Build Excel (.xlsx) workbook via ExcelJS
      const workbook = new ExcelJS.Workbook();
      workbook.creator = "ORDIQ Scheduling Decision-Support System";
      workbook.created = new Date();

      const sheet = workbook.addWorksheet(input.reportType.slice(0, 31));
      sheet.addRow([title]);
      sheet.addRow([`WATERMARK: ${watermark}`]);
      sheet.addRow([
        `Term: ${input.termCode}`,
        `Schedule: ${analytics.candidateLabel}`,
        `Classes Scheduled: ${summaryMetrics.classesScheduled}`,
        `Conflicts: ${summaryMetrics.conflictsDetected}`,
        `Load Balance: ${summaryMetrics.facultyLoadBalanceScore}%`,
        `Room Utilization: ${summaryMetrics.roomUtilizationPct}%`,
      ]);
      sheet.addRow([]);
      sheet.addRow(headers);
      for (const r of rows) {
        sheet.addRow(r);
      }

      const rawArrayBuffer = await workbook.xlsx.writeBuffer();
      const xlsxBuffer = Buffer.from(rawArrayBuffer);

      return {
        fileName: `${baseSlug}.xlsx`,
        mimeType:
          "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        buffer: xlsxBuffer,
        watermark,
        summaryMetrics,
      };
    },
  );
}

